"""Real Unbound bootstrap: separate the HTTPS-origin hostname from the zone.

Local HTTP isolates name-resolution behavior; production HTTPS is checked separately.
Requires /review/nxdomain.zone generated by build_rpz_diagnostic_fixture.php.
"""
import http.server
import os
from pathlib import Path
import socket
import struct
import subprocess
import tempfile
import threading
import time
import unittest


class RpzStartupSafety(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.body = (Path(os.environ['RPZ_SAFETY_OUTPUT']) / 'nxdomain.zone').read_bytes().replace(b'policy.test', b'policy.example.net')
        cls.hits = []
        cls.dns = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        cls.dns.bind(('127.0.0.1', 15300))
        cls.dns.settimeout(0.2)
        cls.stopped = threading.Event()

        def dns_serve():
            while not cls.stopped.is_set():
                try:
                    data, address = cls.dns.recvfrom(4096)
                except socket.timeout:
                    continue
                end = 12
                while data[end]:
                    end += data[end] + 1
                end += 5
                qtype = struct.unpack('!H', data[end - 4:end - 2])[0]
                answer = (b'\xc0\x0c' + struct.pack('!HHIH', 1, 1, 60, 4) + socket.inet_aton('127.0.0.1')) if qtype == 1 else b''
                cls.dns.sendto(data[:2] + struct.pack('!HHHHH', 0x8180, 1, bool(answer), 0, 0) + data[12:end] + answer, address)

        class Handler(http.server.BaseHTTPRequestHandler):
            def do_GET(self):
                cls.hits.append(time.monotonic())
                self.send_response(200)
                self.send_header('Content-Length', str(len(cls.body)))
                self.end_headers()
                self.wfile.write(cls.body)

            def log_message(self, *_):
                pass

        cls.dns_thread = threading.Thread(target=dns_serve, daemon=True)
        cls.dns_thread.start()
        cls.http = http.server.ThreadingHTTPServer(('127.0.0.1', 18080), Handler)
        cls.http_thread = threading.Thread(target=cls.http.serve_forever, daemon=True)
        cls.http_thread.start()

    @classmethod
    def tearDownClass(cls):
        cls.http.shutdown()
        cls.http.server_close()
        cls.stopped.set()
        cls.dns_thread.join(timeout=1)
        cls.dns.close()

    def probe(self, hostname, seeded=False):
        with tempfile.TemporaryDirectory(prefix='rpz-startup-') as directory:
            root = Path(directory)
            saved = root / 'policy.zone'
            if seeded:
                saved.write_bytes(self.body)
            conf = root / 'unbound.conf'
            conf.write_text(f'''server:
 interface: 127.0.0.1@15305
 username: ""
 chroot: ""
 directory: "{root}"
 pidfile: "{root}/pid"
 use-syslog: no
 do-not-query-localhost: no
 so-sndbuf: 0
 module-config: "respip iterator"
forward-zone:
 name: "."
 forward-addr: 127.0.0.1@15300
rpz:
 name: "policy.example.net"
 zonefile: "{saved}"
 url: "http://{hostname}:18080/policy.zone"
''')
            before = len(self.hits)
            with open(root / 'log', 'w') as log:
                process = subprocess.Popen(['unbound', '-d', '-c', str(conf)], stdout=log, stderr=subprocess.STDOUT)
                try:
                    deadline = time.monotonic() + 4
                    while time.monotonic() < deadline:
                        self.assertIsNone(process.poll(), (root / 'log').read_text())
                        if not seeded and saved.exists():
                            break
                        time.sleep(0.05)
                finally:
                    process.terminate()
                    process.wait(timeout=5)
            return len(self.hits) - before, saved.exists(), (root / 'log').read_text()

    def test_same_hostname_reproduces_failed_automatic_lookup(self):
        hits, exists, log = self.probe('policy.example.net')
        self.assertEqual(0, hits)
        self.assertFalse(exists)
        self.assertIn('failed lookup', log)

    def test_separate_hostname_downloads_automatically_without_control_command(self):
        hits, exists, _ = self.probe('download.example.net')
        self.assertGreater(hits, 0)
        self.assertTrue(exists)

    def test_existing_copy_can_be_used_without_immediate_redownload(self):
        hits, exists, _ = self.probe('download.example.net', seeded=True)
        self.assertEqual(0, hits)
        self.assertTrue(exists)


if __name__ == '__main__':
    unittest.main(verbosity=2)
